import { describe, expect, it } from "vitest";
import { classifyPolicy, classifySentence } from "../src/policy.js";

const doc = (text: string) => [{ path: "CONTRIBUTING.md", text }];

describe("classifySentence", () => {
  it.each([
    ["We do not accept pull requests generated by AI tools.", "banned"],
    ["AI-generated contributions are prohibited.", "banned"],
    ["PRs written with ChatGPT or Copilot will be closed.", "banned"],
    ["If you used an LLM, please disclose it in the PR description.", "disclosure-required"],
    ["Undisclosed AI-generated PRs will be rejected.", "disclosure-required"],
    ["AI-assisted contributions must be declared in the PR template.", "disclosure-required"],
    ["Contributors should review any AI tool output before opening a PR.", "rules"],
    ["AI-assisted and generated contributions are welcome.", "allowed"],
    // Real sentences from popular repos' CONTRIBUTING files:
    ["Do not submit AI-generated code you don't understand.", "rules"],
    ["Low-quality or unreviewed AI content will be closed immediately", "rules"],
    ['Do not use "LLM generated" as a justification for low quality code.', "rules"],
    ["Please do not submit AI-generated art, images, video, audio, or diagrams.", "rules"],
    ["**Welcome!** No AI-assistance label or disclosure is required.", "allowed"],
    ["- **Disclosing AI usage (optional)** We are not tracking who used which tool.", "allowed"],
    ["- Be transparent: openly declare that AI was used and explain how it assisted your work in the Pull Request description.", "disclosure-required"],
    ["- [ ] AI assistance was used during the creation of this PR.", "disclosure-required"],
    ["Graphite has ZERO-TOLERANCE for contributing undisclosed AI-generated content.", "disclosure-required"],
    ["**Do not submit vibe-coded or AI generated tools or applications**.", "banned"],
    // From review: ban phrasings that used to slip through, and disclosure edge cases.
    ["We do not allow AI-generated code.", "banned"],
    ["No AI-generated contributions.", "banned"],
    ["We don't allow LLM contributions.", "banned"],
    ["AI contributions are disallowed.", "banned"],
    ["AI-generated code is not accepted, whichever tool was used.", "banned"],
    ["AI-generated PRs with no disclosure will be rejected.", "disclosure-required"],
    ["PRs that use AI with no label will be closed unless disclosed.", "disclosure-required"],
  ])("%s → %s", (sentence, expected) => {
    expect(classifySentence(sentence)).toBe(expected);
  });

  it("ignores AI words that aren't about AI", () => {
    expect(classifySentence("A disabled control must not answer the pointer with an interactive cursor.")).toBeNull();
    expect(classifySentence("We said ai ai captain must not fail.")).toBeNull();
  });

  it("ignores sentences that never mention AI", () => {
    expect(classifySentence("We do not accept PRs without tests.")).toBeNull();
    expect(classifySentence("Please keep PRs small and focused.")).toBeNull();
  });

  it("does not match AI inside other words", () => {
    expect(classifySentence("Do not submit patches that break the main build.")).toBeNull();
    expect(classifySentence("We will not accept changes to the email template.")).toBeNull();
  });
});

describe("classifyPolicy", () => {
  it("returns none when no file mentions AI", () => {
    expect(classifyPolicy(doc("# Contributing\n\nRun the tests before opening a PR.")).class).toBe("none");
  });

  it("returns none when there are no policy files", () => {
    expect(classifyPolicy([])).toEqual({ class: "none", evidence: [], files: [] });
  });

  it("lets a ban win over a disclosure rule in another file", () => {
    const result = classifyPolicy([
      { path: "CONTRIBUTING.md", text: "Please disclose any AI assistance." },
      { path: "AI_POLICY.md", text: "We do not accept AI-generated code." },
    ]);
    expect(result.class).toBe("banned");
    expect(result.evidence).toEqual(["We do not accept AI-generated code."]);
    expect(result.files).toEqual(["CONTRIBUTING.md", "AI_POLICY.md"]);
  });

  it("ignores AI names inside code spans and tables", () => {
    const text = "Changes to `AGENTS.md` (which `CLAUDE.md` points to) must be reviewed.\n\n| Date | Change |\n|---|---|\n| 2026 | Claude must fix |";
    expect(classifyPolicy(doc(text)).class).toBe("none");
  });

  it("treats an explicit welcome as none and plain rules as unknown", () => {
    expect(classifyPolicy(doc("AI-assisted contributions are welcome. You must review AI output.")).class).toBe("none");
    expect(classifyPolicy(doc("You must review AI output before submitting.")).class).toBe("unknown");
  });

  it("reads bullet lists and HTML comments in PR templates", () => {
    const template = "## Checklist\n- [ ] Tests pass\n- [ ] <!-- required --> I have disclosed any AI tools used";
    expect(classifyPolicy(doc(template)).class).toBe("disclosure-required");
  });
});
